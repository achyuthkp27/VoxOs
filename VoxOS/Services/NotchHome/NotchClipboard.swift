import AppKit
import Combine

/// The last few pieces of text copied, on a Clipboard page, to copy again with a click.
///
/// macOS says nothing when the clipboard changes, so its change count is read once a second
/// (with slack for macOS to fold the wake-up into others), and not at all while the displays
/// sleep or the screen is locked. Text a password manager marks as concealed or transient is
/// never kept, and nothing is written to disk: switching this off, or quitting, forgets it.
@MainActor
final class NotchClipboard: ObservableObject {
    static let shared = NotchClipboard()

    struct Item: Identifiable, Equatable {
        let id: UUID
        let text: String
        let at: Date
    }

    static let limit = 8
    static let interval: TimeInterval = 1
    /// Longer copies are kept cut, as the page shows one line of each.
    static let maxCharacters = 2000
    /// Types apps put beside text that must not be remembered (nspasteboard.org's conventions).
    nonisolated static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    @Published private(set) var items: [Item] = []

    private var timer: Timer?
    private var lastCount = 0
    /// The change VoxOS made itself by copying an item back.
    private var ownCount: Int?
    private var awayWatch: AnyCancellable?

    static var isEnabled: Bool { UserDefaults.standard.bool(forKey: DefaultsKeys.notchClipboardEnabled) }

    private init() {}

    func start() {
        guard awayWatch == nil, !ProcessIdentity.isTestHost else { return }
        lastCount = NSPasteboard.general.changeCount
        awayWatch = PowerState.shared.$isAway.receive(on: RunLoop.main).sink { [weak self] away in
            self?.schedule(away: away)
        }
    }

    func stop() {
        awayWatch = nil
        timer?.invalidate()
        timer = nil
        items = []
    }

    private func schedule(away: Bool) {
        timer?.invalidate()
        timer = nil
        guard !away else { return }
        let timer = Timer(timeInterval: Self.interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = Self.interval / 2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func check() {
        let board = NSPasteboard.general
        guard board.changeCount != lastCount else { return }
        lastCount = board.changeCount
        guard lastCount != ownCount, Self.mayKeep(board.types?.map(\.rawValue) ?? []),
            let text = board.string(forType: .string)
        else { return }
        add(text)
    }

    nonisolated static func mayKeep(_ types: [String]) -> Bool {
        !types.contains(where: secretTypes.contains)
    }

    /// Newest first, a repeat moved to the top, past the limit the oldest go.
    func add(_ text: String, now: Date = Date()) {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        let kept = String(trimmed.prefix(Self.maxCharacters))
        items.removeAll { $0.text == kept }
        items.insert(Item(id: UUID(), text: kept, at: now), at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    func copy(_ item: Item) {
        let board = NSPasteboard.general
        board.clearContents()
        board.setString(item.text, forType: .string)
        ownCount = board.changeCount
        add(item.text)
    }
}
